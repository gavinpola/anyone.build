// Mirrors packages/gatekeeper/src/constitution.ts into docs/CONSTITUTION.md (the TS file is the source of truth).
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../packages/gatekeeper/src/constitution.ts", import.meta.url), "utf8");
const version = src.match(/CONSTITUTION_VERSION = "([^"]+)"/)?.[1] ?? "?";
const body = src.match(/CONSTITUTION = `\n([\s\S]*?)`\.trim\(\)/)?.[1] ?? "";
const md = `# The constitution (v${version})\n\nThese are the rules the judge enforces, verbatim. Edited only by humans, via PR.\n\n${body.trim().split("\n").map((l) => l.replace(/^(\d+)\. /, "$1. **").replace(/^(\d+\. \*\*[^.]+\.)/, "$1**")).join("\n\n")}\n`;
writeFileSync(new URL("../docs/CONSTITUTION.md", import.meta.url), md);
// The Rules page renders the same text, so the site and the judge can never drift apart.
const rules = body.trim().split("\n").map((l) => l.replace(/^\d+\. /, "").trim()).filter(Boolean);
writeFileSync(
  new URL("../src/core/lib/constitution.gen.ts", import.meta.url),
  `// generated by scripts/sync-constitution.mjs from packages/gatekeeper/src/constitution.ts — do not edit\nexport const CONSTITUTION_VERSION = ${JSON.stringify(version)};\nexport const CONSTITUTION_RULES: string[] = ${JSON.stringify(rules, null, 2)};\n`,
);
console.log("docs/CONSTITUTION.md and src/core/lib/constitution.gen.ts updated (v" + version + ")");
